"""Tests de bout en bout du mode démonstration : python3 tests/test_annuaire.py
Variables : CHROME (chemin du navigateur), URL (par défaut http://localhost:8790/)."""
import os, sys
from playwright.sync_api import sync_playwright
URL = os.environ.get('URL', 'http://localhost:8790/')
ok = ko = 0
def verifier(nom, cond):
    global ok, ko
    print(('OK   ' if cond else 'ÉCHEC ') + nom); ok += bool(cond); ko += (not cond)
def etat(pg): return pg.evaluate('window.anEtat()')
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=os.environ.get('CHROME') or None, args=['--no-sandbox'])
    pg = b.new_page(viewport={'width': 1280, 'height': 900}); erreurs = []
    pg.on('pageerror', lambda e: erreurs.append(str(e)))
    pg.goto(URL); pg.wait_for_selector('.an-table')
    verifier('liste : 50 lignes par page', pg.locator('.an-table tbody tr').count() == 50)
    verifier('pagination', pg.locator('.an-pagination').count() == 1 and 'Page 1 sur 2' in pg.locator('.an-pagination').inner_text())
    pg.get_by_role('button', name='Page suivante').click()
    verifier('page 2', pg.locator('.an-table tbody tr').count() == 14)
    # Recherche sans accents ni majuscules, focus gardé
    pg.fill('#f-q', 'equipe innovation')
    n = pg.locator('.an-table tbody tr').count()
    verifier('recherche par structure, sans accents', n >= 1 and all('INNOV' in t for t in pg.locator('.an-table tbody tr td:nth-child(2)').all_inner_texts()))
    verifier('le champ de recherche garde le focus', pg.evaluate('document.activeElement.id') == 'f-q')
    pg.fill('#f-q', 'camille martin')
    verifier('recherche : deux fiches Camille Martin', pg.locator('.an-table tbody tr').count() == 2)
    verifier('compteur annoncé', '2 personnes sur 66' in pg.locator('.an-resultat').inner_text())
    pg.fill('#f-q', '')
    pg.select_option('#f-structure', '3')
    verifier('filtre structure avec ses services', all(t.startswith('RECT › DNE') for t in pg.locator('.an-table tbody tr td:nth-child(2)').all_inner_texts()))
    pg.select_option('#f-structure', '')
    pg.select_option('#f-statut', 'archivees')
    verifier('filtre archivées', pg.locator('.an-table tbody tr').count() == 2)
    pg.select_option('#f-statut', 'purge')
    verifier('purge : archivée depuis plus de 12 mois', pg.locator('.an-table tbody tr').count() == 1 and 'Dominique Ancien' in pg.locator('.an-table').inner_text())
    pg.get_by_role('button', name='Supprimer ces 1 fiches').click()
    verifier('purge : confirmation demandée', pg.get_by_role('heading', name='Supprimer définitivement cette fiche ?').count() == 1)
    pg.get_by_role('button', name='Supprimer', exact=True).click(); pg.wait_for_timeout(300)
    verifier('purge : fiche supprimée', etat(pg)['personnes'] == 65)
    pg.select_option('#f-statut', 'actives')
    pg.locator('label[for=f-sans]').click()
    verifier('filtre sans courriel', pg.locator('.an-table tbody tr').count() >= 1 and 'Aucun' in pg.locator('.an-table tbody tr td:nth-child(4)').first.inner_text())
    pg.locator('label[for=f-sans]').click()
    pg.select_option('#f-p-Competences', 'Design')
    verifier('filtre sur un champ personnalisé', pg.locator('.an-table tbody tr').count() >= 1)
    pg.select_option('#f-p-Competences', '')
    # Fiche et « apparaît dans »
    pg.goto(URL + '#/personne/63'); pg.wait_for_selector('.an-infos')
    lat = pg.locator('.an-lateral').inner_text()
    verifier('apparaît dans : projets, groupes, nom en texte', 'Projets' in lat and 'Groupes' in lat and 'Actions de réunion' in lat)
    # Doublons et fusion
    pg.goto(URL + '#/doublons'); pg.wait_for_selector('.an-paire')
    verifier('doublons : 2 paires (nom, courriel)', pg.locator('.an-paire').count() == 2)
    pg.goto(URL + '#/fusion/1/63'); pg.wait_for_selector('[data-fusionner]')
    plan = pg.locator('#an-app').inner_text()
    verifier('fusion : plan détaillé', 'Projets' in plan and 'Groupes' in plan and 'mention' in plan)
    pg.locator('[data-fusionner]').click(); pg.wait_for_timeout(300)
    e = etat(pg)
    gr = {g['id']: g for g in e['autres']['Groupes']}
    pj = {x['id']: x for x in e['autres']['Projets']}
    verifier('fusion : référence simple réécrite', gr[1]['Animation'] == 1)
    verifier('fusion : listes réécrites sans doublon', gr[1]['Membres'] == ['L', 1, 2, 3] and pj[1]['Porteurs'] == ['L', 1])
    verifier('fusion : fiche gardée affichée', pg.locator('h1').inner_text() == 'Camille Martin')
    pg.goto(URL + '#/personne/63'); pg.wait_for_selector('.an-infos')
    verifier('fiche fusionnée : renvoi et archivage', 'Fiche fusionnée dans' in pg.locator('#an-app').inner_text() and 'ARCHIVÉE' in pg.locator('#an-app').inner_text().upper())
    pg.locator('[data-remplacer]').first.click(); pg.wait_for_timeout(300)
    resp = [a['Responsable'] for a in etat(pg)['autres']['Actions_reunion']]
    verifier('mention en texte remplacée', 'Camille Martin' in resp)
    verifier('doublons restants : 1', etat(pg)['doublons'] == 1)
    # Modifier une fiche
    pg.goto(URL + '#/personne/2/modifier'); pg.wait_for_selector('form[data-form=personne]')
    pg.fill('#pf-email', 'adam.david@exemple.fr'); pg.wait_for_timeout(200)
    verifier('alerte courriel déjà utilisé', 'déjà celui de' in pg.locator('#an-app').inner_text())
    pg.fill('#pf-email', 'nouvelle.adresse@exemple.fr'); pg.fill('#pf-nom', 'Nom modifié')
    pg.locator('form[data-form=personne] button[type=submit]').click(); pg.wait_for_selector('.an-infos')
    verifier('fiche modifiée', pg.locator('h1').inner_text() == 'Nom modifié' and 'nouvelle.adresse@exemple.fr' in pg.locator('.an-infos').inner_text())
    pg.get_by_role('button', name='Archiver').click(); pg.wait_for_timeout(200)
    verifier('archiver', 'ARCHIVÉE LE' in pg.locator('#an-app').inner_text().upper())
    pg.get_by_role('button', name='Réactiver').click(); pg.wait_for_timeout(200)
    verifier('réactiver', 'ARCHIVÉE LE' not in pg.locator('#an-app').inner_text().upper())
    # Structures
    pg.goto(URL + '#/structures'); pg.wait_for_selector('.an-arbre')
    verifier('arborescence des structures', pg.locator('.an-arbre > li').count() == 5 and pg.locator('.an-arbre ul ul').count() >= 1)
    pg.goto(URL + '#/nouvelle-structure/3'); pg.wait_for_selector('form[data-form=structure]')
    pg.fill('#sf-nom', 'Équipe accessibilité'); pg.locator('form[data-form=structure] button[type=submit]').click(); pg.wait_for_selector('.an-infos')
    verifier('service créé sous sa structure', 'RECT › DNE › Équipe accessibilité' in pg.locator('.an-infos').inner_text())
    pg.goto(URL + '#/structure/9'); pg.wait_for_selector('.an-infos')
    pg.get_by_role('button', name='Supprimer').click(); pg.get_by_role('button', name='Supprimer', exact=True).last.click(); pg.wait_for_timeout(300)
    e = etat(pg)
    verifier('structure supprimée, personnes détachées', e['structures'] == 10 and pg.evaluate('window.anEtat().personnes') > 0)
    # Import
    pg.goto(URL + '#/importer'); pg.wait_for_selector('#imp-texte', state='attached')
    pg.locator('details summary').click()
    pg.fill('#imp-texte', 'Prénom;Nom;Courriel;Service;Fonction\nAnne;Nouvelle;anne.nouvelle@exemple.fr;DATA;Statisticienne\nCamille;Martin;;INNOV;\nX;Y;adresse-invalide;;\nBob;Neuf;bob.neuf@exemple.fr;Mission inconnue;\n')
    pg.get_by_role('button', name='Lire ce contenu').click(); pg.wait_for_selector('.an-apercu-import')
    txt = pg.locator('#an-app').inner_text()
    verifier('import : colonnes devinées et aperçu', '2 nouvelle(s), 1 doublon(s) probable(s), 0 déjà présente(s), 1 en erreur' in txt)
    pg.get_by_role('button', name='Importer 2 personne(s)').click(); pg.wait_for_selector('.an-table')
    e = etat(pg)
    verifier('import : 2 personnes, 1 structure créée', e['structures'] == 11 and 'importée' in pg.locator('.an-alerte').inner_text())
    pg.fill('#f-q', 'anne nouvelle')
    verifier('import : structure reconnue par son sigle', 'DATA' in pg.locator('.an-table tbody tr').first.inner_text())
    # Ma fiche
    pg.goto(URL + '#/moi'); pg.wait_for_selector('h1'); pg.wait_for_timeout(400)
    verifier('ma fiche : ouverte par le courriel', pg.locator('h1').inner_text() == 'Camille Martin')
    # Réglages : champ personnalisé
    pg.locator('.cl-barre label', has_text='Réglages').click(); pg.wait_for_timeout(300)
    pg.locator('[data-rg-ajouter]').click(); pg.wait_for_timeout(200)
    n = pg.locator('.an-champ-perso').count()
    pg.fill('#rg-p-lib-' + str(n - 1), 'Équipe projet')
    pg.select_option('#rg-p-type-' + str(n - 1), 'choix'); pg.wait_for_timeout(200)
    pg.fill('#rg-p-lib-' + str(n - 1), 'Équipe projet'); pg.fill('#rg-p-opt-' + str(n - 1), 'Alpha\nBêta')
    pg.get_by_role('button', name='Enregistrer').first.click(); pg.wait_for_timeout(300)
    verifier('réglages : champ personnalisé ajouté', any(c['col'] == 'Equipe_projet' for c in etat(pg)['reglages']['champsPerso']))
    pg.locator('.cl-barre label').first.click(); pg.wait_for_timeout(300)
    pg.goto(URL + '#/personne/1/modifier'); pg.wait_for_selector('#pf-Equipe_projet')
    pg.select_option('#pf-Equipe_projet', 'Bêta'); pg.locator('form[data-form=personne] button[type=submit]').click(); pg.wait_for_selector('.an-infos')
    verifier('champ personnalisé saisi et affiché', 'Bêta' in pg.locator('.an-infos').inner_text())
    # Aperçu réel
    pg.goto(URL); pg.wait_for_selector('.an-table')
    pg.locator('.cl-barre label', has_text='Aperçu').click(); pg.wait_for_timeout(500)
    verifier('aperçu réel', pg.locator('.cl-apercu #an-app .an-table').count() == 1)
    pg.locator('.cl-barre label').first.click(); pg.wait_for_timeout(300)
    verifier('mention d\'information affichée', 'gestionnaires de l\'annuaire' in pg.locator('.an-mention').inner_text())
    pg.screenshot(path='/tmp/annuaire.png', full_page=True)
    verifier('aucune erreur JavaScript', not erreurs)
    if erreurs: print(erreurs)
    b.close()
print(f'{ok} réussis, {ko} échoués'); sys.exit(1 if ko else 0)
